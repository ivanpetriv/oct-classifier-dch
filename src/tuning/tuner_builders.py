"""
Builds a config for Optuna trial.

Every run Optuna trial uses different values. Because the configuration provides a fixed
set of hyperparameters, every trial must build a new one
using values generated by search_space.py functions.
"""

import optuna

from config.oct_config import (
    ClassificationOption,
    DimensionalityReductionOption,
    FeatureExtractionOption,
    PreprocessingOption,
)
from tuning.search_space import (
    ClassifierTuners,
    FeatureExtractorTuners,
    PreprocessingTuners,
    ReducerTuners,
)


def create_preprocessing_tuner(
    preprocessing_config: list[PreprocessingOption],
    trial: optuna.Trial,
) -> list[PreprocessingOption]:
    """Tunes preprocessing steps and returns updated config."""
    tuned_config: list[PreprocessingOption] = []

    for index, step_config in enumerate(preprocessing_config):
        step_dict = step_config.model_dump(exclude_none=True)
        config_class = type(step_config)

        for step_name in step_dict:
            tuner_fn = PreprocessingTuners.REGISTRY.get(step_name)
            if tuner_fn is not None:
                step_dict[step_name] = tuner_fn(
                    trial,
                    prefix=f"{step_name}_{index}",
                )

        tuned_step = config_class.model_validate(step_dict)
        tuned_config.append(tuned_step)

    return tuned_config


